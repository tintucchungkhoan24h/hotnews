// 2. Đọc spoke URLs mới từ file JSON (được tạo bởi generate-digest*.mjs)
function loadSpokeUrls(filename) {
  const filepath = path.join(ROOT, filename);
  if (!fs.existsSync(filepath)) return [];
  try {
    const urls = JSON.parse(fs.readFileSync(filepath, 'utf8'));
    // Clean up the file after reading
    fs.unlinkSync(filepath);
    console.log(`  📂 Loaded ${urls.length} spoke URL(s) from ${filename}`);
    return Array.isArray(urls) ? urls : [];
  } catch (e) {
    console.warn(`  ⚠️ Could not parse ${filename}:`, e.message);
    return [];
  }
}

// 3. Xác thực với Google API bằng file JSON tạm thời do GitHub Actions sinh ra
const KEY_FILE = './service_account.json';

if (!fs.existsSync(KEY_FILE)) {
  console.error(`❌ Không tìm thấy file cấu hình xác thực tại: ${KEY_FILE}`);
  process.exit(1);
}

const auth = new google.auth.GoogleAuth({
  keyFile: KEY_FILE,
  scopes: ['https://www.googleapis.com/auth/indexing'],
});

const indexing = google.indexing({
  version: 'v3',
  auth: auth,
});

// 4. Hàm gửi request Ping tới Google
async function pingUrl(url) {
  try {
    const response = await indexing.urlNotifications.publish({
      requestBody: {
        url: url,
        type: 'URL_UPDATED', // Thông báo URL được cập nhật/thêm mới nội dung
      },
    });
    console.log(`✅ Đã ping thành công: ${url} (Trạng thái: ${response.statusText || 'OK'})`);
  } catch (error) {
    console.error(`❌ Lỗi khi ping URL [${url}]:`, error.message);
  }
}

// 5. Duyệt qua danh sách và thực thi tuần tự
async function main() {
  // Load new spoke URLs generated by the digest scripts
  const spokeUrlsMacro = loadSpokeUrls('spoke_urls_macro.json');
  const spokeUrlsStock = loadSpokeUrls('spoke_urls_stock.json');
  const spokeUrlsWorldNews = loadSpokeUrls('spoke_urls_world_news.json');
  
  // Load year-split spoke URLs too (in case there are any left)
  const currentYear = new Date().getFullYear();
  const yearSplitFiles = [
    `spoke_urls_macro_${currentYear}.json`,
    `spoke_urls_stock_${currentYear}.json`,
    `spoke_urls_world_news_${currentYear}.json`,
  ];
  
  let allYearSplitUrls = [];
  for (const file of yearSplitFiles) {
    const urls = loadSpokeUrls(file);
    allYearSplitUrls = [...allYearSplitUrls, ...urls];
  }
  
  // Combine: hub URLs (always) + new spoke URLs (only if new)
  const allUrls = [
    ...HUB_URLS,
    ...spokeUrlsMacro,
    ...spokeUrlsStock,
    ...spokeUrlsWorldNews,
    ...allYearSplitUrls,
  ];

  // Deduplicate
  const uniqueUrls = [...new Set(allUrls)];

  console.log(`🚀 Bắt đầu gửi ${uniqueUrls.length} URLs lên Google Indexing API...`);
  console.log(`   (${HUB_URLS.length} hub + ${spokeUrlsMacro.length} macro spoke + ${spokeUrlsStock.length} stock spoke + ${spokeUrlsWorldNews.length} world news spoke)`);
  
  for (const url of uniqueUrls) {
    await pingUrl(url);
    // Tránh gửi quá dồn dập, nghỉ 200ms giữa mỗi request
    await new Promise(resolve => setTimeout(resolve, 200));
  }
  
  console.log('🏁 Hoàn thành quá trình gọi Google Indexing!');
}

main();